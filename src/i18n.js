// Lets the running app pick up Admin-edited translations without a rebuild: overrides are
// fetched from the server once at boot (see main.jsx / admin/main.jsx) and merged directly on
// top of the strings baked into this bundle. Every t()/tf() call reads from `translations`, so
// nothing else needs to know overrides exist.
export function applyTranslationOverrides(overrides) {
  if (!overrides || typeof overrides !== "object") return;
  for (const [language, entries] of Object.entries(overrides)) {
    if (!entries || typeof entries !== "object") continue;
    if (!translations[language]) translations[language] = {};
    for (const [key, value] of Object.entries(entries)) {
      if (typeof value === "string" && value.trim()) translations[language][key] = value;
    }
  }
}

// The full set of source (English) keys — the definitive list of every translatable string in
// the running app, always in sync since it comes straight from the same object t()/tf() read.
export function allTranslationKeys() {
  return Object.keys(translations.en);
}

export function translationFor(language, key) {
  return translations[language]?.[key];
}

